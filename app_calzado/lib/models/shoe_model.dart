class ShoeModel {
  final String id;
  final String name;
  final String category;
  final String subcategory;
  final String price;
  final double rating;
  final String image;
  final String badge;

  ShoeModel({
    required this.id,
    required this.name,
    required this.category,
    required this.subcategory,
    required this.price,
    required this.rating,
    required this.image,
    required this.badge,
  });
}